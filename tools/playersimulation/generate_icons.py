def main():
    colors = {'.': (0, 0, 0, 0), 'W': (242, 242, 242, 255), 'S': (77, 77, 103, 255)}
    atlas = Image.new('RGBA', (16 * len(PATTERNS), 16))
    for i, rows in enumerate(PATTERNS.values()):
        for y, row in enumerate(rows):
            for x, pixel in enumerate(row):
                atlas.putpixel((i * 16 + x, y), colors[pixel])
    target = Path('src/main/resources/assets/chexsonsaeutils/textures/gui/player_simulation_icons.png')
    target.parent.mkdir(parents=True, exist_ok=True)
    atlas.save(target)
    preview = Image.new('RGB', (9 * 88, 3 * 106), '#b8bcc5')
    graphics = ImageDraw.Draw(preview)
    for i, name in enumerate(PATTERNS):
        x, y = (i % 9) * 88 + 12, (i // 9) * 106 + 8
        graphics.rectangle((x - 4, y - 4, x + 65, y + 69), fill='#9295a0', outline='#555555', width=2)
        icon = atlas.crop((i * 16, 0, i * 16 + 16, 16)).resize((64, 64), Image.Resampling.NEAREST)
        preview.paste(icon, (x, y), icon)
        graphics.text((x - 4, y + 74), name, fill='#242424')
    Path('build').mkdir(exist_ok=True)
    preview.save('build/player-simulation-icons-preview.png')


if __name__ == '__main__':
    main()
